#!/usr/bin/env python3
"""Build the website (docs/, served by GitHub Pages) from src/.

src/ is the only place anything is written by hand:

    src/overlay.html          the overlay itself (what OBS shows)
    src/web/index.html        the setup page people use to make their OBS link
    src/web/engine.js         fetches the player's ranked data (through the
                              Worker in web/) and works out what the overlay shows
    src/web/logo.svg          the site icon (favicon-32.png and
                              apple-touch-icon.png are renders of it)
    src/web/og.png            the picture link previews show (Discord, X, ...)
    src/web/sitemap.xml,
    src/web/llms.txt          what search engines and AI assistants read
    src/web/preview/*.html    unlisted pages, served at docs/preview/<name>/

Run it after touching anything in src/. CI runs it with --check to make sure
docs/ actually matches src/.

    python tools/build.py            rebuild docs/
    python tools/build.py --check    fail if docs/ is out of date
"""

import argparse
import hashlib
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
WEB = os.path.join(SRC, "web")
DOCS = os.path.join(ROOT, "docs")


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n")


# If engine.js didn't arrive (a network blip as OBS starts, say), the page
# would sit dead until someone refreshed the source by hand. Reload it instead,
# backing off from 5 seconds to a minute so a real outage isn't hammered.
ENGINE_GUARD = (
    "if (!window.RankedEngine) { var n = 0; "
    "try { n = +sessionStorage.getItem('vro-reloads') || 0; sessionStorage.setItem('vro-reloads', n + 1); } catch (e) {} "
    "setTimeout(function () { location.reload(); }, Math.min(60000, 5000 * Math.pow(2, n))); } "
    "else { try { sessionStorage.removeItem('vro-reloads'); } catch (e) {} }"
)


def asset_version(text):
    """Short content hash, so OBS never pairs a new page with an old engine."""
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]


def page(path, version):
    """A page that loads engine.js: fill in its version and the reload guard."""
    html = read(path)
    for hook in ("__ENGINE_VERSION__", "__ENGINE_GUARD__"):
        if html.count(hook) != 1:
            raise SystemExit(f"{os.path.relpath(path, ROOT)}: expected one {hook}, found {html.count(hook)}")
    name = os.path.relpath(path, ROOT).replace(os.sep, "/")
    html = html.replace("__ENGINE_VERSION__", version).replace("__ENGINE_GUARD__", ENGINE_GUARD)
    return html.replace("<head>", f"<head>\n    <!-- Generated by tools/build.py from {name}. Edit that file, not this one. -->", 1)


def web_outputs():
    """The GitHub Pages site, as ({path: text}, {path: source file to copy})."""
    files, binaries = {}, {}
    engine = read(os.path.join(WEB, "engine.js"))
    version = asset_version(engine)

    files[os.path.join(DOCS, "engine.js")] = engine
    files[os.path.join(DOCS, "index.html")] = page(os.path.join(WEB, "index.html"), version)
    files[os.path.join(DOCS, "overlay.html")] = page(os.path.join(SRC, "overlay.html"), version)
    files[os.path.join(DOCS, "logo.svg")] = read(os.path.join(WEB, "logo.svg"))
    # For search engines and AI assistants: the one page worth indexing, and a
    # plain-text summary (llmstxt.org).
    for name in ("sitemap.xml", "llms.txt"):
        files[os.path.join(DOCS, name)] = read(os.path.join(WEB, name))
    # Serve the files as they are, without Jekyll looking at them first.
    files[os.path.join(DOCS, ".nojekyll")] = ""
    for name in ("favicon-32.png", "apple-touch-icon.png", "og.png"):
        binaries[os.path.join(DOCS, name)] = os.path.join(WEB, name)

    # Unlisted pages: src/web/preview/<name>.html -> docs/preview/<name>/.
    preview = os.path.join(WEB, "preview")
    for name in sorted(os.listdir(preview)):
        if name.endswith(".html"):
            files[os.path.join(DOCS, "preview", name[:-5], "index.html")] = read(os.path.join(preview, name))
    return files, binaries


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def same_bytes(a, b):
    try:
        with open(a, "rb") as fa, open(b, "rb") as fb:
            return fa.read() == fb.read()
    except OSError:
        return False


def current(path):
    try:
        with open(path, encoding="utf-8", newline="") as f:
            return f.read().replace("\r\n", "\n")
    except OSError:
        return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report drift instead of rewriting anything")
    args = ap.parse_args()

    web_files, web_binaries = web_outputs()
    stale = [p for p, text in web_files.items() if current(p) != text]
    stale += [dst for dst, src in web_binaries.items() if not same_bytes(dst, src)]

    # Anything left in docs/ that the build no longer makes.
    owned = set(web_files) | set(web_binaries)
    orphans = []
    if os.path.isdir(DOCS):
        for folder, _dirs, names in os.walk(DOCS):
            for name in names:
                path = os.path.join(folder, name)
                if path not in owned:
                    orphans.append(path)

    total = len(web_files) + len(web_binaries)
    if args.check:
        if stale or orphans:
            print("These files in docs/ no longer match src/:\n")
            for p in sorted(stale + orphans):
                print("  " + os.path.relpath(p, ROOT))
            print("\nRun: python tools/build.py")
            return 1
        print(f"Up to date ({total} generated files).")
        return 0

    for p, text in web_files.items():
        write(p, text)
    for dst, src in web_binaries.items():
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
    for p in orphans:
        os.remove(p)
    print(f"Wrote {total} files into docs/.")
    if stale:
        print(f"{len(stale)} of them changed.")
    if orphans:
        print(f"Removed {len(orphans)} stale file(s) from docs/.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
